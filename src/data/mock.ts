function buildReviews(seed: number, count: number): Review[] {
  return Array.from({ length: count }, (_, index) => {
    const base = reviewPool[(seed + index) % reviewPool.length];
    const reviewDay = -4 - index * 6 - (seed % 5);
    return {
      id: `rev_${seed}_${index}`,
      author: base.author,
      initials: base.author
        .split(' ')
        .map((part) => part[0])
        .join(''),
      rating: base.rating,
      date: iso(reviewDay),
      comment: base.comment,
      verified: index % 3 !== 1,
    };
  });
}

